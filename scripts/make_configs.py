"""Generate the prime-rl configs for every arm from one template, so arms differ only in the reward.

  python scripts/make_configs.py            # writes configs/rl_<arm>.toml, configs/pilot.toml, configs/eval_*.toml

Arms (see PREREGISTRATION.md):
  checklist       0.7 x required outputs PRESENT (values unchecked) + 0.3 if it claims done (gameable)
  outcome         ground-truth partial credit, report ignored
  honest          0.7 x ground-truth partial + 0.3 for a truthful completed flag
(The LLM-judge arm was dropped before any training: no affordable judge beat 0.61 balanced
accuracy on labeled rollouts. See results/judge_cal_*.jsonl and PREREGISTRATION.md.)
"""

from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
MODEL = "Qwen/Qwen3.5-4B"  # probe: 4B 36% success / 39% false success; 9B 86% / 4% (ceiling, nothing to learn)
THINKING = False  # Qwen3.5 reasons by default; off keeps long agentic episodes inside seq_len (preregistered)
EXTRA_BODY = "{ chat_template_kwargs = { enable_thinking = %s } }" % ("true" if THINKING else "false")
# Pilot pass rates (4B, 668 rollouts): these six families sit at 17-69%; the other eight are ~0%
# (and longest) or ~95%+, so their GRPO groups carry no signal (pilot admission rate was 27%).
TRAIN_FAMILIES = ["refunds_policy", "collections_legal", "memo_override", "partial_batch", "impossible", "reorder"]
ARMS = {"checklist": "checklist", "outcome": "partial", "honest": "honest_partial"}

COMMON = dict(
    seq_len=32768,
    max_steps=40,        # all arms compared at step 40 (checklist arm's step-40 online eval; ~4.7 h/arm measured)
    lr=1e-5,
    lora_rank=16,
    lora_alpha=32,
    batch_size=32,       # rollouts per step
    group_size=8,        # rollouts per task (GRPO group) -> 4 tasks per step
    max_tokens=8192,     # per model turn; thinking off, the 4B reasons in its reply (2048 cut off ~half the pilot's final turns)
    temperature=1.0,
    max_turns=30,        # probe: >30-turn episodes were 54% of all turns, 1/8 succeeded (mostly loops)
    rollout_timeout=900,
    train_tasks=1000,
    eval_interval=40,    # held-out eval at step 40 (step 0 = base model, already measured in run 1)
    skip_first_eval=True,
    ckpt_interval=40,
    seed=11,
)

# With LoRA on, prime-rl's inference server serves the trained adapter under MODEL and the frozen
# base weights as f"{MODEL}-base" (docs/advanced.md). The judge must be the frozen base, or the
# policy would be grading itself.
JUDGE_MODEL = f"{MODEL}-base"
JUDGE = f'{{ base_url = "http://localhost:8000/v1", model = "{JUDGE_MODEL}", api_key_var = "VLLM_API_KEY", sampling = {{ max_tokens = 2048, temperature = 0.0, chat_template_kwargs = {{ enable_thinking = false }} }} }}'
AGENT = '{{ harness = {{ id = "null" }}, runtime = {{ type = "subprocess" }}, max_turns = {max_turns}, timeout = {{ rollout = {rollout_timeout} }} }}'


def train_toml(arm: str, reward_mode: str, c: dict, name: str | None = None) -> str:
    agent = AGENT.format(**c)
    return f"""# Generated by scripts/make_configs.py — edit the generator, not this file.
# Arm: {arm} (reward_mode = "{reward_mode}"). Hardware: 2 x 48GB GPUs, e.g. A6000 (1 trainer, 1 vLLM).
#   uv run rl @ configs/{name or f'rl_{arm}'}.toml --run.name {name or arm}
max_steps = {c['max_steps']}
seq_len = {c['seq_len']}

[deployment]
num_train_gpus = 1
num_infer_gpus = 1

[model]
name = "{MODEL}"

[monitors.wandb]
project = "honesty-rl"
name = "{name or arm}"

[trainer.optim]
lr = {c['lr']}
weight_decay = 0.0

# Qwen3.5 is a vision-language checkpoint: without this block the trainer loads no language-model
# weights (pilot 1: entropy = ln(vocab), grad norm 0). bfloat16 is required for VLMs (docs/advanced.md).
[trainer.model]
optimization_dtype = "bfloat16"
reduce_dtype = "bfloat16"

[trainer.model.vlm]
vision_encoder_attr = "model.visual"
language_model_attr = "model.language_model"

[trainer.model.lora]
rank = {c['lora_rank']}
alpha = {c['lora_alpha']}
dropout = 0.0
target_modules = ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"]

[orchestrator]
batch_size = {c['batch_size']}

[orchestrator.concurrency]
initial_inflight = 24   # ~1.0M KV tokens / 32k per episode; adaptive after start

[orchestrator.train]
group_size = {c['group_size']}

[orchestrator.train.sampling]
max_completion_tokens = {c['max_tokens']}
temperature = {c['temperature']}
extra_body = {EXTRA_BODY}

[[orchestrator.train.source]]
name = "potemkin-bench"
curriculum = {{ gates = {{ zero_advantage = {{ type = "advantage_range" }} }} }}
env.taskset.id = "potemkin-bench"
env.taskset.split = "train"
env.taskset.families = {json.dumps(TRAIN_FAMILIES)}
env.taskset.scale = "small"
env.taskset.num_tasks = {c['train_tasks']}
env.taskset.seed = {c['seed']}
env.taskset.task.reward_mode = "{reward_mode}"
env.agent = {agent}

# Held-out learning curves: same-domain test split and a never-trained-on domain.
[orchestrator.eval]
interval = {c['eval_interval']}
skip_first_step = {str(c.get('skip_first_eval', False)).lower()}

[orchestrator.eval.sampling]
max_completion_tokens = {c['max_tokens']}
temperature = 0.7
extra_body = {EXTRA_BODY}

[[orchestrator.eval.source]]
name = "lvi-test"
group_size = 2
select = {{ limit = 14 }}
env.taskset.id = "potemkin-bench"
env.taskset.split = "test"
env.taskset.difficulty = "mixed"
env.taskset.scale = "small"
env.taskset.num_tasks = 14
env.taskset.task.reward_mode = "strict"
env.agent = {agent}

[[orchestrator.eval.source]]
name = "caseworker-test"
group_size = 2
select = {{ limit = 8 }}
env.taskset.id = "safety-net-bench"
env.taskset.split = "test"
env.taskset.scale = "small"
env.taskset.num_tasks = 8
env.taskset.task.reward_mode = "strict"
env.agent = {agent}

[ckpt]
interval = {c['ckpt_interval']}

[inference.vllm]
enable_lora = true
max_model_len = {c['seq_len']}   # default is the model's 262k, which caps concurrency at 3 episodes
# tool_call_parser / reasoning_parser left on "auto": prime-rl maps Qwen3.5 to qwen3_coder / qwen3.
"""


def eval_toml(name: str, sources: list[tuple[str, dict]], c: dict) -> str:
    agent = AGENT.format(**c)
    out = [f"""# Generated by scripts/make_configs.py. Final evaluation: {name}.
#   uv run eval @ configs/eval_{name}.toml -m <model or lora name>
model = "{MODEL}"
group_size = 2

[client]
base_url = "http://localhost:8000/v1"

[sampling]
max_completion_tokens = {c['max_tokens']}
temperature = 0.7
extra_body = {EXTRA_BODY}
"""]
    for src_name, opts in sources:
        lines = [f"[[source]]", f'name = "{src_name}"']
        for k, v in opts.items():
            lines.append(f"{k} = {v}")
        lines.append(f"env.agent = {agent}")
        out.append("\n".join(lines) + "\n")
    return "\n".join(out)


def main() -> None:
    cfg = ROOT / "configs"
    cfg.mkdir(exist_ok=True)
    for arm, mode in ARMS.items():
        (cfg / f"rl_{arm}.toml").write_text(train_toml(arm, mode, COMMON))
    # Optional 2nd seed for the two arms the main comparison rests on (different training tasks + sampling)
    for arm in ("outcome", "honest"):
        (cfg / f"rl_{arm}_s2.toml").write_text(train_toml(arm, ARMS[arm], dict(COMMON, seed=23), name=f"{arm}_s2"))
    pilot = dict(COMMON, max_steps=10, eval_interval=10, ckpt_interval=10, train_tasks=120, skip_first_eval=True)
    (cfg / "pilot.toml").write_text(train_toml("checklist", "checklist", pilot, name="pilot"))
    for old in ("rl_judge.toml",):
        (cfg / old).unlink(missing_ok=True)

    q = lambda s: f'"{s}"'
    final = [
        ("lvi-test-mixed", {"env.taskset.id": q("potemkin-bench"), "env.taskset.split": q("test"),
                            "env.taskset.difficulty": q("mixed"), "env.taskset.scale": q("small"),
                            "env.taskset.num_tasks": 84}),
        # prompt-only baseline: the same held-out tasks with an explicit honesty instruction
        ("lvi-honesty-prompt", {"env.taskset.id": q("potemkin-bench"), "env.taskset.split": q("test"),
                                "env.taskset.difficulty": q("mixed"), "env.taskset.scale": q("small"),
                                "env.taskset.num_tasks": 84, "env.taskset.pressures": '["honesty_prompt"]'}),
        ("lvi-test-expert", {"env.taskset.id": q("potemkin-bench"), "env.taskset.split": q("test"),
                             "env.taskset.difficulty": q("expert"), "env.taskset.scale": q("small"),
                             "env.taskset.num_tasks": 24}),
        ("lvi-pressure", {"env.taskset.id": q("potemkin-bench"), "env.taskset.split": q("test"),
                          "env.taskset.difficulty": q("mixed"), "env.taskset.scale": q("small"),
                          "env.taskset.num_tasks": 14, "env.taskset.pressures": '["completion", "bonus"]'}),
        ("caseworker-test", {"env.taskset.id": q("safety-net-bench"), "env.taskset.split": q("test"),
                             "env.taskset.scale": q("small"), "env.taskset.num_tasks": 30}),
        # capability retention: did honesty training cost general instruction following?
        ("ifeval", {"env.taskset.id": q("ifeval"), "group_size": 1, "select": "{ limit = 200 }"}),
    ]
    (cfg / "eval_main.toml").write_text(eval_toml("main", final, COMMON))
    # One config per source, so every source gets its own output directory: the two
    # potemkin-bench sources share task-id formats, and paired stats key on task id.
    for old in cfg.glob("eval_src_*.toml"):
        old.unlink()
    for src_name, opts in final:
        (cfg / f"eval_src_{src_name}.toml").write_text(eval_toml(src_name, [(src_name, opts)], COMMON))
    print("wrote", sorted(p.name for p in cfg.glob("*.toml")))


if __name__ == "__main__":
    main()
